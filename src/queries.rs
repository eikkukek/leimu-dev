pub struct QueryPoolAttributes<'a> {
    pub tag: Option<&'a str>,
    pub query_type: QueryType,
}

bitflags::bitflags! {
    /// A bitmask of pipeline statistic query types.
    #[repr(transparent)]
    #[derive(Default, Clone, Copy, Zeroable, ByteEq, ByteHash, Debug)]
    pub struct PipelineStatisticQueryType: u32 {
        /// The query counts the number of vertices processed by the input assembly state.
        const INPUT_ASSEMBLY_VERTICES = 0x0001;
        /// The query counts the number of primitives processed by the input assembly state.
        const INPUT_ASSEMBLY_PRIMITIVES = 0x0002;
        /// The query counts the number of vertex shader invocations.
        const VERTEX_SHADER_INVOCATIONS = 0x0004;
        /// The query counts the number of geometry shader invocations.
        const GEOMETRY_SHADER_INVOCATIONS = 0x0008;
        /// The query counts the number of primitives generated by geometry shader invocations. 
        const GEOMETRY_SHADER_PRIMITIVES = 0x0010;
        /// The query counts the number of primitives processed by the [Primitive Clipping] stage.
        /// The counter's value is incremented each time a primitive reaches the primitive clipping
        /// stage.
        ///
        /// [Primitive Clipping]: https://docs.vulkan.org/spec/latest/chapters/vertexpostproc.html#vertexpostproc-clipping
        const CLIPPING_INVOCATIONS = 0x0020;
        /// The query counts the number of primitives output by the [Primitive Clipping] stage.
        /// The counter's value is incremented each time a primitive passes the primitive clipping
        /// stage.
        ///
        /// [Primitive Clipping]: https://docs.vulkan.org/spec/latest/chapters/vertexpostproc.html#vertexpostproc-clipping
        const CLIPPING_PRIMITIVES = 0x0040;
        /// The query counts the number of fragment shader invocations.
        const FRAGMENT_SHADER_INVOCATIONS = 0x0080;
        /// The query counts the number of patches processed by the tessellation control shader.
        const TESSELLATION_CONTROL_SHADER_PATCHES = 0x0100;
        /// The query counts the number of tesellation evaluation shader invocations.
        const TESSELLATION_EVALUATION_SHADER_INVOCATIONS = 0x0200;
        /// The query counts the number of compute shader invocations.
        const COMPUTE_SHADER_INVOCATIONS = 0x0400;
        /// The query counts the number of task shader invocations.
        ///
        /// # Valid usage
        /// - The [`mesh_shader_queries`][vk_ext::mesh_shader_queries] feature **must** be enabled.
        const TASK_SHADER_INVOCATIONS_EXT = 0x0800;
        /// The query counts the number of mesh shader invocations.
        ///
        /// # Valid usage
        /// - The [`mesh_shader_queries`][vk_ext::mesh_shader_queries] feature **must** be enabled.
        const MESH_SHADER_INVOCATIONS_EXT = 0x1000;
    }
}
unsafe impl NoUninit for PipelineStatisticQueryType {}
__bitflags_display!(PipelineStatisticQueryType);
impl From<PipelineStatisticQueryType> for vk::QueryPipelineStatisticFlags {
    #[inline]
    fn from(value: PipelineStatisticQueryType) -> Self {
        Self::from_raw(value.bits())
    }
}

/// The type of queries a query pool will track.
#[derive(Clone, Copy)]
pub enum QueryType {
    /// Specifies an occlusion query, which tracks the number of samples that pass the per-fragment
    /// test for a set of drawing commands.
    Occlusion,
    /// Specifies a timestamp query. It behaves differently from other queries in that they don't
    /// operate over a range, but instead are explicitly written by [`write_time_stamp`] commands.
    Timestamp,
    /// Specifies a generated mesh primitives query. The counter is incremented every time a
    /// primitive emitted from the mesh shader reaches the fragment shader stage.
    ///
    /// # Valid usage
    /// - The [`mesh_shader_queries`][vk_ext::mesh_shader_queries] feature **must** be enabled.
    MeshPrimiviesGeneratedEXT,
    /// Specifies a pipeline statistics query. The details of available queries are documented in
    /// the bits of [`PipelineStatisticQueryType`].
    ///
    /// # Valid usage
    /// - The [`pipeline_statistics_query`] feature **must** be enabled.
    ///
    /// [`pipeline_statistics_query`]: vk_10::pipeline_statistics_query
    PipelineStatistics(PipelineStatisticQueryType),
}

